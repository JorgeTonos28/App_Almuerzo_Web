import fs from 'node:fs/promises';
import { compile } from '@vue/compiler-dom';
const html = await fs.readFile('src/Almuerzo.Web/Templates/app.html', 'utf8');
const template = html.match(/<div id="app"[^>]*>([\s\S]*)<\/div>\s*<script src="\/assets\/rpc.js">/)?.[1];
if (!template || html.includes('<?')) throw new Error('Template must be fully ported from Apps Script.');
const { code } = compile(template, { mode: 'function', prefixIdentifiers: true, hoistStatic: true });
const logic = await fs.readFile('frontend/app.js', 'utf8');
if (!logic.includes('render: AlmuerzoRender')) throw new Error('The application must use the precompiled render function.');
await fs.writeFile('src/Almuerzo.Web/wwwroot/assets/app.js', `// Generated by npm run build. Edit frontend/app.js and Templates/app.html.\nconst AlmuerzoRender = (() => {\n${code}\n})();\n${logic}`);
